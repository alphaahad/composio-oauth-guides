import { Suspense } from "react";
import Link from "next/link";
import { notFound } from "next/navigation";
import { Badge, ClaimList, ClaimView } from "@/components/Claims";
import { CopyButton } from "@/components/CopyButton";
import { guideToMarkdown, VERDICT_LABEL, VERDICT_TONE } from "@/lib/present";
import { getGuide } from "@/lib/store";

const SURFACE_LABEL = {
  api: "Creatable via API",
  cli: "Scriptable via CLI",
  manifest: "Manifest-driven, human step remains",
  "ui-only": "Web UI only",
  gated: "Human or provider gate",
  unknown: "Unknown",
} as const;

// Live guides are created at request time, so params and the store read sit behind Suspense
// (Cache Components requires runtime data to be streamed, not blocking the static shell).
export default function GuidePage({ params }: PageProps<"/g/[slug]">) {
  return (
    <Suspense
      fallback={
        <main className="wrap">
          <p className="muted">Loading guide…</p>
        </main>
      }
    >
      {params.then(({ slug }) => (
        <GuideContent slug={slug} />
      ))}
    </Suspense>
  );
}

async function GuideContent({ slug }: { slug: string }) {
  const g = await getGuide(slug);
  if (!g) notFound();

  const tone = VERDICT_TONE[g.verdict.value];
  const okSources = g.sources.filter((s) => s.status === "ok");
  const failedSources = g.sources.filter((s) => s.status !== "ok");

  return (
    <main className="wrap">
      <title>{`${g.appName}: OAuth app setup`}</title>
      <div className="topbar">
        <Link href="/">← All guides</Link>
        <span className="muted">Generated {g.generatedAt.slice(0, 10)}</span>
      </div>

      <h1>{g.appName}</h1>
      {g.humanReviewed ? (
        <p className="notice notice-good">Reviewed by a human. Evidence is shown under each claim.</p>
      ) : (
        <p className="notice">Generated by an agent and not human-verified. Quotes were checked by code against the fetched pages; open “Evidence” before relying on a claim.</p>
      )}

      <section className="banner" aria-labelledby="verdict">
        <span id="verdict" className={`chip chip-${tone}`}>
          Verdict
        </span>
        <p className="verdict">
          {VERDICT_LABEL[g.verdict.value]} <Badge level={g.verdict.claim.confidence} />
        </p>
        <p>{g.summary}</p>
        {g.verdict.claim.evidence.length > 0 && <ClaimView claim={{ ...g.verdict.claim, text: "Why:" }} />}
        <p style={{ marginTop: "0.75rem" }}>
          <strong>Do you need your own app?</strong> {g.composio.note}
        </p>
      </section>

      <section className="gauges" aria-label="At a glance">
        <div className="gauge">
          <h3>Effort</h3>
          <ClaimView claim={g.effort} />
        </div>
        <div className="gauge">
          <h3>Approval wait</h3>
          <ClaimView claim={g.wait} />
        </div>
        <div className="gauge">
          <h3>Blocker risk</h3>
          <ClaimView claim={g.blockerRisk.claim} />
        </div>
      </section>

      <div className="actions">
        <CopyButton label="Copy as Markdown" text={guideToMarkdown(g)} />
        <CopyButton label="Copy link" text="" getUrl />
      </div>

      <h2>Steps</h2>
      <ClaimList claims={g.steps} ordered />

      <h2>Redirect URI rules</h2>
      <ClaimList claims={g.redirectRules} />

      <h2>Requirements</h2>
      <ClaimList claims={g.requirements} />

      {g.scopeTiers.length > 0 && (
        <>
          <h2>Scope tiers</h2>
          <ClaimList claims={g.scopeTiers} />
        </>
      )}

      <h2>Gotchas</h2>
      <ClaimList claims={g.gotchas} />

      <h2>What an agent can do, and where you take over</h2>
      <p className="muted">Setup surface: {SURFACE_LABEL[g.automation.surface]}</p>
      <div className="two">
        <div className="panel">
          <h3>Agent can</h3>
          <ClaimList claims={g.automation.agentCan} />
        </div>
        <div className="panel">
          <h3>You must</h3>
          <ClaimList claims={g.automation.youMust} />
        </div>
      </div>

      <h2>If you are blocked</h2>
      <div className="two">
        <div className="panel">
          <h3>Who to contact</h3>
          <ClaimList claims={g.blocked.contacts} />
        </div>
        <div className="panel">
          <h3>Why submissions get rejected</h3>
          <ClaimList claims={g.blocked.usualRejections} />
        </div>
      </div>
      {g.blocked.emailTemplate && (
        <>
          <h3 style={{ marginTop: "1rem" }}>Email template</h3>
          <pre className="template">{g.blocked.emailTemplate}</pre>
          <CopyButton label="Copy template" text={g.blocked.emailTemplate} />
        </>
      )}

      {g.probes.length > 0 && (
        <>
          <h2>What we probed (no credentials)</h2>
          <table className="sources">
            <tbody>
              {g.probes.map((p, i) => (
                <tr key={i}>
                  <th scope="row">{p.name}</th>
                  <td>
                    <code>{p.url}</code>
                    <br />
                    {p.ok ? "Found: " : "Not found: "}
                    {p.finding}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </>
      )}

      <h2>What we could not verify</h2>
      {g.gaps.length === 0 ? (
        <p className="muted">No gaps recorded.</p>
      ) : (
        <ul>
          {g.gaps.map((x, i) => (
            <li key={i}>{x}</li>
          ))}
        </ul>
      )}

      <h2>Sources</h2>
      <table className="sources">
        <thead>
          <tr>
            <th>Page</th>
            <th>Fetched</th>
            <th>Note</th>
          </tr>
        </thead>
        <tbody>
          {okSources.map((s, i) => (
            <tr key={i}>
              <td>
                <a href={s.url} target="_blank" rel="noopener noreferrer">
                  {s.title || s.url}
                </a>
              </td>
              <td>{s.fetchedAt.slice(0, 10)}</td>
              <td>{s.note}</td>
            </tr>
          ))}
          {failedSources.map((s, i) => (
            <tr key={`f${i}`}>
              <td>{s.url}</td>
              <td>{s.fetchedAt.slice(0, 10)}</td>
              <td>Could not read: {s.note}</td>
            </tr>
          ))}
        </tbody>
      </table>
    </main>
  );
}

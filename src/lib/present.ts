import type { Claim, Confidence, Guide, Verdict } from "./schema";

export const VERDICT_LABEL: Record<Verdict, string> = {
  "no-approval-needed": "No approval needed",
  "self-serve-with-review-for-listing": "Works immediately; review only to be listed",
  "review-required": "Provider review required before real users can connect",
  "partner-gated": "Partner-gated access",
  "no-oauth": "No OAuth (uses another auth method)",
  unknown: "Verdict unknown",
};

export const VERDICT_TONE: Record<Verdict, "good" | "okay" | "warn" | "bad" | "muted"> = {
  "no-approval-needed": "good",
  "self-serve-with-review-for-listing": "okay",
  "review-required": "warn",
  "partner-gated": "bad",
  "no-oauth": "muted",
  unknown: "muted",
};

export const CONFIDENCE_LABEL: Record<Confidence, string> = {
  tested: "Tested by us",
  docs: "From official docs",
  reported: "Reported (community)",
  inferred: "Our estimate",
  conflicting: "Sources conflict",
  unknown: "Unverified",
};

export const CONFIDENCE_HELP: Record<Confidence, string> = {
  tested: "We ran this ourselves and saved the evidence.",
  docs: "A verbatim quote was found on a fetched official page.",
  reported: "A verbatim quote from a third-party page; not official.",
  inferred: "Our judgment derived from other findings; not stated by a source.",
  conflicting: "Sources disagree; see the evidence.",
  unknown: "No source supports this; treat it as a gap.",
};

const bullets = (claims: Claim[]) => claims.map((c) => `- ${c.text} _[${CONFIDENCE_LABEL[c.confidence]}${c.support === "partial" ? ", partly supported" : ""}]_`).join("\n");

/** Plain-markdown export so a guide can be pasted into a ticket or chat. */
export function guideToMarkdown(g: Guide, shareUrl?: string): string {
  const out: string[] = [];
  out.push(`# ${g.appName}: OAuth app setup`);
  if (shareUrl) out.push(`Source: ${shareUrl}`);
  out.push(
    g.humanReviewed
      ? `_Reviewed by a human. Generated ${g.generatedAt.slice(0, 10)}._`
      : `_Generated by an agent on ${g.generatedAt.slice(0, 10)}; not human-verified. Check the evidence before relying on it._`,
  );
  out.push(`## Verdict\n**${VERDICT_LABEL[g.verdict.value]}** _[${CONFIDENCE_LABEL[g.verdict.claim.confidence]}]_\n\n${g.summary}`);
  out.push(`**Composio:** ${g.composio.note}`);
  out.push(
    `## At a glance\n- Effort: ${g.effort.text} _[${CONFIDENCE_LABEL[g.effort.confidence]}]_\n- Approval wait: ${g.wait.text} _[${CONFIDENCE_LABEL[g.wait.confidence]}]_\n- Blocker risk: ${g.blockerRisk.claim.text}`,
  );
  const sections: [string, Claim[]][] = [
    ["Steps", g.steps],
    ["Redirect URI rules", g.redirectRules],
    ["Requirements", g.requirements],
    ["Scope tiers", g.scopeTiers],
    ["Gotchas", g.gotchas],
    ["What an agent can do", g.automation.agentCan],
    ["What you must do", g.automation.youMust],
    ["If you are blocked: contacts", g.blocked.contacts],
    ["Why submissions get rejected", g.blocked.usualRejections],
  ];
  for (const [title, claims] of sections) if (claims.length) out.push(`## ${title}\n${bullets(claims)}`);
  if (g.blocked.emailTemplate) out.push(`## Email template\n${g.blocked.emailTemplate}`);
  if (g.gaps.length) out.push(`## What we could not verify\n${g.gaps.map((x) => `- ${x}`).join("\n")}`);
  const ok = g.sources.filter((s) => s.status === "ok");
  if (ok.length) out.push(`## Sources\n${ok.map((s) => `- ${s.url} (fetched ${s.fetchedAt.slice(0, 10)})`).join("\n")}`);
  return out.join("\n\n") + "\n";
}
